package com.myqaweb.teststudio;

/**
 * Test Studio v2.5 보조 설정 — 생성될 TC의 문체/어조 힌트.
 *
 * <p>스타일 예시 세트가 있으면 예시가 우선하며, 이 값은 예시가 없을 때의 약한 힌트다.
 */
public enum Tone {
    /** 개조식 (예: "이메일 입력함", "로그인 성공함"). */
    BULLET,
    /** 격식체 (예: "이메일을 입력합니다", "성공합니다"). */
    FORMAL,
    /** 평서체 (예: "이메일을 입력한다", "성공한다") — 현재 기본. */
    PLAIN
}
